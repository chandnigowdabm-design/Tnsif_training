package org.thnisf.ace.c2tc.wrapperclass;

public class WrapperclassDemo {

	public static void main(String[] args) {
		
		 byte primitiveByte = 1;
	        Byte wrapperByte = primitiveByte;      
	        System.out.println(wrapperByte);

	        byte unboxByte = wrapperByte;           
	        System.out.println(unboxByte);


	        // SHORT
	        short primitiveShort = 2;
	        Short wrapperShort = primitiveShort;     
	        System.out.println(wrapperShort);

	        short unboxShort = wrapperShort;         
	        System.out.println(unboxShort);


	        // INT
	        int primitiveInt = 3;
	        Integer wrapperInt = primitiveInt;       
	        System.out.println(wrapperInt);

	        int unboxInt = wrapperInt;               
	        System.out.println(unboxInt);


	        // LONG
	        long primitiveLong = 4L;
	        Long wrapperLong = primitiveLong;        
	        System.out.println(wrapperLong);

	        long unboxLong = wrapperLong;             
	        System.out.println(unboxLong);


	        // FLOAT
	        float primitiveFloat = 5.5f;
	        Float wrapperFloat = primitiveFloat;     
	        System.out.println(wrapperFloat);

	        float unboxFloat = wrapperFloat;         
	        System.out.println(unboxFloat);


	        // DOUBLE
	        double primitiveDouble = 6.6;
	        Double wrapperDouble = primitiveDouble;  
	        System.out.println(wrapperDouble);

	        double unboxDouble = wrapperDouble;      
	        System.out.println(unboxDouble);


	        // CHAR
	        char primitiveChar = 'A';
	        Character wrapperChar = primitiveChar;   
	        System.out.println(wrapperChar);

	        char unboxChar = wrapperChar;           
	        System.out.println(unboxChar);


	        // BOOLEAN
	        boolean primitiveBoolean = true;
	        Boolean wrapperBoolean = primitiveBoolean; 
	        System.out.println(wrapperBoolean);

	        boolean unboxBoolean = wrapperBoolean;      
	        System.out.println(unboxBoolean);
	    }
	
	

	}


